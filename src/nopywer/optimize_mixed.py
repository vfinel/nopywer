def assign_tiers_to_nodes(
    tree: nx.DiGraph,
    nodes: dict,
    dist_matrix: dict,
) -> dict:
    """
    Assigns the minimum cable tier to each edge that satisfies:
    - current capacity >= cumulative flow
    - voltage drop <= threshold
    Returns {(from, to): CableTier}
    """
    generator = next(n for n, node in nodes.items() if node.is_generator)
    cable_tiers = {}

    for node_i, node_j in nx.bfs_edges(tree, source=generator):
        # Cumulative flow = sum of all descendant loads
        subtree_nodes = nx.descendants(tree, node_j) | {node_j}
        flow_w = sum(
            nodes[n].power_watts
            for n in subtree_nodes
            if not nodes[n].is_generator
        )
        current_a = flow_w / (V0 * PF)
        d = dist_matrix[(node_i, node_j)]

        # Select minimum tier that satisfies both constraints
        selected_tier = None
        for tier in sorted(_CABLE_TYPES, key=lambda t: t.area_mm2):  # smallest first
            # Capacity check
            if tier.max_current_a < current_a:
                continue
            # Voltage drop check
            resistance_total = (RHO_COPPER / tier.area_mm2) * d
            vdrop_pct = 100 * current_a * resistance_total / V0
            if vdrop_pct > VDROP_THRESHOLD_PERCENT:
                continue
            selected_tier = tier
            break

        if selected_tier is None:
            # No tier satisfies constraints — use largest available and warn
            selected_tier = max(_CABLE_TYPES, key=lambda t: t.area_mm2)
            logger.warning(
                f"[TIER] No suitable tier for {node_i}→{node_j}: "
                f"flow={flow_w:.0f}W, current={current_a:.1f}A, d={d:.0f}m — "
                f"using largest tier ({selected_tier.area_mm2}mm²)"
            )

        cable_tiers[(node_i, node_j)] = selected_tier
        logger.debug(
            f"[TIER] {node_i}→{node_j}: {selected_tier.area_mm2}mm² "
            f"({current_a:.1f}A, {d:.0f}m)"
        )

    return cable_tiers

def define_distance_matrix(nodes, names, dist_matrix):
    for a, b in itertools.permutations(names, 2):
        na = nodes[a]
        nb = nodes[b]
        d = geodesic_distance_m(
            na.lon,
            na.lat,
            nb.lon,
            nb.lat,
        )
        dist_matrix[(a, b)] = d
